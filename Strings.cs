        public static bool IsChinese { get; private set; }

        public static void Init(string langSetting)
        {
            bool zh;
            if (langSetting == "zh-CN") zh = true;
            else if (langSetting == "en-US") zh = false;
            else zh = CultureInfo.InstalledUICulture.TwoLetterISOLanguageName == "zh";
            IsChinese = zh;
        }

        public static string T(string key)
        {
            var dict = IsChinese ? Zh : En;
            string value;
            return dict.TryGetValue(key, out value) ? value : key;
        }
